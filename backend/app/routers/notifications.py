@router.get("", response_model=List[NotificationResponse])
def get_notifications(
    user_id: Optional[str] = None,
    filter_type: Optional[str] = Query(None, description="All, unread, timetable, exams, rescheduling, venues, alert"),
    db: Session = Depends(get_db)
):
    """
    Returns notifications list with unread state, type formatting, and role/user scoping.
    """
    ensure_comprehensive_notifications(db)

    query = db.query(Notification)
    if user_id:
        query = query.filter((Notification.user_id == user_id) | (Notification.user_id.is_(None)))

    if filter_type:
        ft = filter_type.lower()
        if ft == "unread":
            query = query.filter(Notification.read == False)
        elif ft in ["timetable", "exams", "rescheduling", "venues"]:
            query = query.filter(Notification.link_module == ft)
        elif ft in ["alert", "warning", "info", "success"]:
            query = query.filter(Notification.type == ft)

    notifications = query.order_by(Notification.created_at.desc()).all()

    results = []
    for n in notifications:
        resp = NotificationResponse(
            id=n.id,
            user_id=n.user_id,
            title=n.title,
            description=n.description,
            type=n.type or "info",
            read=n.read,
            link_module=n.link_module,
            link_sub_page=n.link_sub_page,
            created_at=n.created_at,
            time=_format_time_ago(n.created_at)
        )
        results.append(resp)
    return results

@router.get("/stream")
async def stream_notifications(request: Request):
    """
    Real-Time Server-Sent Events (SSE) notification stream.
    Pushes real-time alerts and unread counters to connected frontend clients.
    """
    async def event_generator() -> AsyncGenerator[str, None]:
        last_count = -1
        while True:
            if await request.is_disconnected():
                break

            db = SessionLocal()
            try:
                unread = db.query(Notification).filter(Notification.read == False).count()
                total = db.query(Notification).count()

                # Always yield initial sync or when unread count changes
                if unread != last_count or last_count == -1:
                    last_count = unread
                    payload = {
                        "event": "notification_update",
                        "unread_count": unread,
                        "total_count": total,
                        "timestamp": datetime.utcnow().isoformat()
                    }
                    yield f"data: {json.dumps(payload)}\n\n"
                else:
                    # Heartbeat ping
                    yield f": ping {datetime.utcnow().isoformat()}\n\n"
            finally:
                db.close()

            await asyncio.sleep(5)

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        }
    )

@router.post("", response_model=NotificationResponse)
def create_notification(
    notif_in: NotificationCreate,
    db: Session = Depends(get_db)
):
    notif = Notification(
        id=f"notif-{uuid.uuid4().hex[:8]}",
        user_id=notif_in.user_id,
        title=notif_in.title,
        description=notif_in.description,
        type=notif_in.type,
        read=notif_in.read,
        link_module=notif_in.link_module,
        link_sub_page=notif_in.link_sub_page,
        created_at=datetime.utcnow()
    )
    db.add(notif)
    db.commit()
    db.refresh(notif)
    return NotificationResponse(
        id=notif.id,
        user_id=notif.user_id,
        title=notif.title,
        description=notif.description,
        type=notif.type,
        read=notif.read,
        link_module=notif.link_module,
        link_sub_page=notif.link_sub_page,
        created_at=notif.created_at,
        time="Just now"
    )

@router.post("/{notification_id}/read", response_model=NotificationResponse)
@router.put("/{notification_id}/read", response_model=NotificationResponse)
def mark_as_read(notification_id: str, db: Session = Depends(get_db)):
    notif = db.query(Notification).filter(Notification.id == notification_id).first()
    if not notif:
        raise HTTPException(status_code=404, detail="Notification not found")
    notif.read = True
    db.commit()
    db.refresh(notif)
    return NotificationResponse(
        id=notif.id,
        user_id=notif.user_id,
        title=notif.title,
        description=notif.description,
        type=notif.type,
        read=notif.read,
        link_module=notif.link_module,
        link_sub_page=notif.link_sub_page,
        created_at=notif.created_at,
        time=_format_time_ago(notif.created_at)
    )

@router.post("/mark-all-read")
@router.post("/clear-all")
def clear_all_notifications(db: Session = Depends(get_db)):
    db.query(Notification).update({Notification.read: True})
    db.commit()
    return {"success": True, "message": "All notifications marked as read"}

@router.delete("/{notification_id}")
def delete_notification(notification_id: str, db: Session = Depends(get_db)):
    notif = db.query(Notification).filter(Notification.id == notification_id).first()
    if not notif:
        raise HTTPException(status_code=404, detail="Notification not found")
    db.delete(notif)
    db.commit()
    return {"success": True, "message": f"Notification {notification_id} deleted successfully"}
